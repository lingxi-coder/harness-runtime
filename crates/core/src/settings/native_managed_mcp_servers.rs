#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct NativeManagedMcpServerDiagnostic {
    /// The callback path supplied by `qt`: empty for an invalid root,
    /// `<invalid name>` for a bad key, or the actual server name.
    pub callback_path: Utf16JsonProjection,
    /// The message supplied by `qt` before `__` adds its warning prefix.
    pub message: Utf16JsonProjection,
    pub raw_value: Option<Utf16JsonProjection>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct NativeManagedMcpServersResult {
    /// `None` means Native `qt` returned undefined, so `__` removes the field.
    /// `Some({})` means the root was a valid map but no member survived.
    pub normalized: Option<Utf16JsonProjection>,
    /// Ordered exactly as JavaScript `Object.entries` visits the source map.
    pub diagnostics: Vec<NativeManagedMcpServerDiagnostic>,
    /// If true, the normalized projection is diagnostic-only and must not be
    /// used to admit this static-settings candidate.
    pub unresolved: bool,
}

/// Collect URL-constructor inputs reached by the Native managed-MCP map
/// walk. OAuth metadata URLs are included only after the outer URL, scanner,
/// and preceding OAuth fields allow `normalize_oauth` to reach them.
pub(crate) fn collect_native_managed_mcp_semantic_inputs(
    servers: &Utf16JsonProjection,
    semantics: Option<&NativePolicyJsSemanticsRegistry>,
    url_inputs: &mut Vec<Vec<u16>>,
) {
    let Some(root) = servers.at_pointer("") else {
        return;
    };
    let Some(entries) = js_ordered_entries(root) else {
        return;
    };
    for entry in entries {
        let Ok(server) = servers.subprojection_property_units(entry.code_units) else {
            continue;
        };
        let Some(server_root) = server.at_pointer("") else {
            continue;
        };
        if server_root.object_entries().is_none()
            || BANNED_KEYS.iter().any(|key| server.contains_property(key))
        {
            continue;
        }
        let Some(type_units) = server_root
            .get_property("type")
            .and_then(JsonValueView::code_units)
        else {
            continue;
        };
        if !["http", "streamable-http", "sse"]
            .iter()
            .any(|kind| ascii_eq(type_units, kind))
        {
            continue;
        }
        let Some(url_units) = server_root
            .get_property("url")
            .and_then(JsonValueView::code_units)
        else {
            continue;
        };
        super::native_policy::NativePolicySemanticInputs::push_unique(
            url_inputs,
            url_units.to_vec(),
        );

        let Some(row) = semantics.and_then(|semantics| semantics.url(url_units)) else {
            continue;
        };
        let NativePolicyZodUrlOutcome::Valid {
            protocol_units,
            hostname_units,
            ..
        } = &row.zod_url
        else {
            continue;
        };
        if protocol_units != &ascii_units("https:")
            || hostname_units.is_empty()
            || scan_entry_strings(server_root).is_some()
            || server_root
                .get_property("headers")
                .is_some_and(|headers| !is_string_record(headers))
        {
            continue;
        }
        let Some(oauth) = server_root.get_property("oauth") else {
            continue;
        };
        if oauth.object_entries().is_none()
            || oauth
                .get_property("clientId")
                .is_some_and(|value| value.code_units().is_none())
            || oauth
                .get_property("callbackPort")
                .is_some_and(|value| !is_positive_integer(value))
        {
            continue;
        }
        if let Some(auth_url) = oauth
            .get_property("authServerMetadataUrl")
            .and_then(JsonValueView::code_units)
        {
            super::native_policy::NativePolicySemanticInputs::push_unique(
                url_inputs,
                auth_url.to_vec(),
            );
        }
    }
}

#[must_use]
pub(crate) fn normalize_native_managed_mcp_servers(
    value: &Utf16JsonProjection,
    semantics: &NativePolicyJsSemanticsRegistry,
) -> NativeManagedMcpServersResult {
    let Some(root) = value.at_pointer("") else {
        return unresolved_result(value);
    };
    let Some(entries) = js_ordered_entries(root) else {
        return NativeManagedMcpServersResult {
            normalized: None,
            diagnostics: vec![NativeManagedMcpServerDiagnostic {
                callback_path: string_projection(""),
                message: string_projection(ROOT_SHAPE_MESSAGE),
                raw_value: Some(value.clone()),
            }],
            unresolved: false,
        };
    };

    let mut normalized_entries = Vec::with_capacity(entries.len());
    let mut diagnostics = Vec::new();
    let mut unresolved = false;

    for entry in entries {
        if !native_server_name(entry.code_units) {
            diagnostics.push(NativeManagedMcpServerDiagnostic {
                callback_path: string_projection("<invalid name>"),
                message: string_projection(INVALID_NAME_MESSAGE),
                raw_value: value.subprojection_property_units(entry.code_units).ok(),
            });
            continue;
        }

        let Ok(server) = value.subprojection_property_units(entry.code_units) else {
            unresolved = true;
            continue;
        };
        match normalize_server(&server, semantics) {
            ServerResult::Kept(normalized_server) => {
                normalized_entries.push((entry.code_units.to_vec(), normalized_server));
            }
            ServerResult::Dropped(message) => diagnostics.push(NativeManagedMcpServerDiagnostic {
                callback_path: string_projection_units(entry.code_units),
                message,
                raw_value: Some(server),
            }),
            ServerResult::Unresolved => {
                unresolved = true;
                normalized_entries.push((entry.code_units.to_vec(), server));
            }
        }
    }

    let normalized = Utf16JsonProjection::object_units(normalized_entries).ok();
    if normalized.is_none() {
        unresolved = true;
    }
    NativeManagedMcpServersResult {
        normalized,
        diagnostics,
        unresolved,
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum ServerResult {
    Kept(Utf16JsonProjection),
    Dropped(Utf16JsonProjection),
    Unresolved,
}

fn normalize_server(
    server: &Utf16JsonProjection,
    semantics: &NativePolicyJsSemanticsRegistry,
) -> ServerResult {
    let Some(root) = server.at_pointer("") else {
        return ServerResult::Unresolved;
    };
    let Some(_entries) = js_ordered_entries(root) else {
        return ServerResult::Dropped(string_projection(&invalid_record_type(root)));
    };

    // The source schema checks these own properties in this fixed order,
    // before checking `type`, `url`, or traversing nested strings.
    for key in BANNED_KEYS {
        if server.contains_property(key) {
            return ServerResult::Dropped(string_projection(&format!(
                "{key}: \"{key}\" is not allowed in managed settings: only http/sse URL servers can be delivered this way, and a managed settings document must not name a program to run"
            )));
        }
    }

    let type_units = root
        .get_property("type")
        .and_then(JsonValueView::code_units)
        .unwrap_or(&[]);
    let (normalized_type, is_streamable_http) = if ascii_eq(type_units, "http") {
        ("http", false)
    } else if ascii_eq(type_units, "streamable-http") {
        ("http", true)
    } else if ascii_eq(type_units, "sse") {
        ("sse", false)
    } else {
        return ServerResult::Dropped(string_projection(&format!("type: {TYPE_MESSAGE}")));
    };

    let url_view = root.get_property("url");
    let Some(url_units) = url_view.and_then(JsonValueView::code_units) else {
        // Native's `to()` custom check does not emit its URL refinement when
        // the field is missing or non-string; it still runs the nested-string
        // scanner, whose first issue is surfaced by `qt` before the object
        // schema's generic invalid-input issue.
        if let Some(message) = scan_entry_strings(root) {
            return ServerResult::Dropped(message);
        }
        return ServerResult::Dropped(string_projection("Invalid input"));
    };
    let Some(url_row) = semantics.url(url_units) else {
        return ServerResult::Unresolved;
    };
    let NativePolicyZodUrlOutcome::Valid {
        protocol_units,
        hostname_units,
        zod_value_units,
        ..
    } = &url_row.zod_url
    else {
        return ServerResult::Dropped(string_projection(&format!("url: {URL_MESSAGE}")));
    };
    if protocol_units != &ascii_units("https:") || hostname_units.is_empty() {
        return ServerResult::Dropped(string_projection(&format!("url: {URL_MESSAGE}")));
    }
    let normalized_url = string_projection_units(zod_value_units);

    if let Some(message) = scan_entry_strings(root) {
        return ServerResult::Dropped(message);
    }

    let url = normalized_url;

    let headers = root.get_property("headers");
    if headers.is_some_and(|value| !is_string_record(value)) {
        return ServerResult::Dropped(string_projection("Invalid input"));
    }
    let oauth = match root.get_property("oauth") {
        Some(_) => match normalize_oauth(server, semantics) {
            Ok(value) => Some(value),
            Err(NormalizeValueError::Invalid) => {
                return ServerResult::Dropped(string_projection("Invalid input"));
            }
            Err(NormalizeValueError::Unresolved) => return ServerResult::Unresolved,
        },
        None => None,
    };
    let timeout = root.get_property("timeout");
    if timeout.is_some_and(|value| !is_positive_integer(value)) {
        return ServerResult::Dropped(string_projection("Invalid input"));
    }
    let tools = match root.get_property("tools") {
        Some(value) => match normalize_tools(server, value) {
            Ok(value) => Some(value),
            Err(()) => return ServerResult::Dropped(string_projection("Invalid input")),
        },
        None => None,
    };
    for key in ["alwaysLoad", "bareElicitationCapability", "discoveryCache"] {
        if root
            .get_property(key)
            .is_some_and(|value| value.as_bool().is_none())
        {
            return ServerResult::Dropped(string_projection("Invalid input"));
        }
    }
    let tool_permissions = match root.get_property("toolPermissions") {
        Some(value) => match normalize_tool_permissions(server, value) {
            Ok(value) => Some(value),
            Err(()) => return ServerResult::Dropped(string_projection("Invalid input")),
        },
        None => None,
    };

    let request_timeout = root.get_property("request_timeout_ms");
    let accepted_request_timeout = request_timeout.filter(|value| is_positive_integer(*value));
    let timeout_present = timeout.is_some();

    let mut output = Vec::new();
    output.push((ascii_units("type"), string_projection(normalized_type)));
    output.push((ascii_units("url"), url));
    if headers.is_some() {
        output.push((
            ascii_units("headers"),
            normalize_string_record(server, "headers"),
        ));
    }
    if let Some(oauth) = oauth {
        output.push((ascii_units("oauth"), oauth));
    }
    if timeout_present {
        output.push((
            ascii_units("timeout"),
            project_root_field(server, "timeout"),
        ));
    }
    if let Some(tools) = tools {
        output.push((ascii_units("tools"), tools));
    }
    for key in ["alwaysLoad", "bareElicitationCapability", "discoveryCache"] {
        if root.get_property(key).is_some() {
            output.push((ascii_units(key), project_root_field(server, key)));
        }
    }
    if root
        .get_property("role")
        .and_then(JsonValueView::code_units)
        .is_some_and(|value| ascii_eq(value, "comms"))
    {
        output.push((ascii_units("role"), project_root_field(server, "role")));
    }
    if let Some(tool_permissions) = tool_permissions {
        output.push((ascii_units("toolPermissions"), tool_permissions));
    }
    if !timeout_present {
        if let Some(request_timeout) = accepted_request_timeout {
            let request_timeout = request_timeout.as_number().unwrap_or(0.0);
            let folded_timeout = request_timeout.min(300_000.0);
            output.push((ascii_units("timeout"), number_projection(folded_timeout)));
        }
    }

    // The Native HTTP schema maps `streamable-http` to `http` before MAr.
    debug_assert!(is_streamable_http || ascii_eq(type_units, normalized_type));
    match Utf16JsonProjection::object_units(output) {
        Ok(normalized) => ServerResult::Kept(normalized),
        Err(_) => ServerResult::Unresolved,
    }
}

#[derive(Clone, Copy)]
enum NormalizeValueError {
    Invalid,
    Unresolved,
}

fn scan_entry_strings(root: JsonValueView<'_>) -> Option<Utf16JsonProjection> {
    scan_value(root, &[], 0, false)
}

fn scan_value(
    value: JsonValueView<'_>,
    path: &[u16],
    depth: usize,
    is_key: bool,
) -> Option<Utf16JsonProjection> {
    if let Some(units) = value.code_units() {
        if contains_source_control(units) {
            return Some(path_message(path, CONTROL_MESSAGE));
        }
        if !is_key && contains_native_env_reference(units) {
            return Some(path_message(path, ENV_MESSAGE));
        }
        return None;
    }
    if depth > 4 {
        return None;
    }
    if let Some(entries) = js_ordered_entries(value) {
        for entry in entries {
            let component = escaped_source_component(entry.code_units);
            let child_path = join_path(path, &component);
            let key_projection = string_projection_units(entry.code_units);
            if let Some(message) =
                scan_value(key_projection.at_pointer("")?, &child_path, depth, true)
            {
                return Some(message);
            }
            if let Some(message) = scan_value(entry.value, &child_path, depth + 1, false) {
                return Some(message);
            }
        }
        return None;
    }
    if let Some(length) = value.array_len() {
        for index in 0..length {
            let Some(child) = value.get_index(index) else {
                continue;
            };
            let component = ascii_units(&index.to_string());
            let child_path = join_path(path, &component);
            if let Some(message) = scan_value(child, &child_path, depth + 1, false) {
                return Some(message);
            }
        }
    }
    None
}

fn escaped_source_component(units: &[u16]) -> Vec<u16> {
    let mut output = Vec::new();
    let mut index = 0;
    while index < units.len() {
        let (code_point, width) = code_point_at(units, index);
        if is_source_control(code_point) {
            output.extend(format!("\\u{code_point:04x}").encode_utf16());
        } else {
            output.extend_from_slice(&units[index..index + width]);
        }
        index += width;
    }
    output
}

fn contains_source_control(units: &[u16]) -> bool {
    let mut index = 0;
    while index < units.len() {
        let (code_point, width) = code_point_at(units, index);
        if is_source_control(code_point) {
            return true;
        }
        index += width;
    }
    false
}

fn code_point_at(units: &[u16], index: usize) -> (u32, usize) {
    let first = u32::from(units[index]);
    if (0xd800..=0xdbff).contains(&first) {
        if let Some(second) = units.get(index + 1).copied().map(u32::from) {
            if (0xdc00..=0xdfff).contains(&second) {
                let high = first - 0xd800;
                let low = second - 0xdc00;
                return (0x10000 + ((high << 10) | low), 2);
            }
        }
    }
    (first, 1)
}

fn is_source_control(code_point: u32) -> bool {
    SOURCE_CONTROL_RANGES
        .iter()
        .any(|(start, end)| (*start..=*end).contains(&code_point))
}

fn contains_native_env_reference(units: &[u16]) -> bool {
    let is_start = |unit: u16| matches!(unit, 65..=90 | 95 | 97..=122);
    let is_continue = |unit: u16| is_start(unit) || matches!(unit, 48..=57);
    let mut index = 0;
    while index + 2 < units.len() {
        if units[index] != 36 || units[index + 1] != 123 || !is_start(units[index + 2]) {
            index += 1;
            continue;
        }
        index += 3;
        while index < units.len() && is_continue(units[index]) {
            index += 1;
        }
        if index + 1 < units.len() && units[index] == 58 && units[index + 1] == 45 {
            index += 2;
            while index < units.len() && units[index] != 125 {
                index += 1;
            }
        }
        if index < units.len() && units[index] == 125 {
            return true;
        }
    }
    false
}

fn native_server_name(units: &[u16]) -> bool {
    // Native uses `/^[A-Za-z0-9_-]+$/` without multiline mode; the whole key
    // must consist only of these ASCII code units.
    if units.is_empty()
        || units
            .iter()
            .any(|unit| !matches!(*unit, 45 | 48..=57 | 65..=90 | 95 | 97..=122))
    {
        return false;
    }
    !ascii_eq(units, "__proto__")
        && !ascii_eq(units, "constructor")
        && !ascii_eq(units, "prototype")
}

fn invalid_record_type(value: JsonValueView<'_>) -> String {
    let received = if value.is_null() {
        "null"
    } else if value.array_len().is_some() {
        "array"
    } else if value.code_units().is_some() {
        "string"
    } else if value.as_bool().is_some() {
        "boolean"
    } else {
        "number"
    };
    format!("Invalid input: expected record, received {received}")
}

fn is_positive_integer(value: JsonValueView<'_>) -> bool {
    let Some(number) = value.as_number() else {
        return false;
    };
    number.is_finite() && number > 0.0 && number.fract() == 0.0
}

fn is_string_record(value: JsonValueView<'_>) -> bool {
    js_ordered_entries(value).is_some_and(|entries| {
        entries
            .iter()
            .all(|entry| entry.value.code_units().is_some())
    })
}

fn normalize_oauth(
    server: &Utf16JsonProjection,
    semantics: &NativePolicyJsSemanticsRegistry,
) -> Result<Utf16JsonProjection, NormalizeValueError> {
    let oauth = server
        .subprojection_property_units(&ascii_units("oauth"))
        .map_err(|_| NormalizeValueError::Unresolved)?;
    let root = oauth
        .at_pointer("")
        .ok_or(NormalizeValueError::Unresolved)?;
    js_ordered_entries(root).ok_or(NormalizeValueError::Invalid)?;

    let mut fields = Vec::new();
    if let Some(value) = root.get_property("clientId") {
        if value.code_units().is_none() {
            return Err(NormalizeValueError::Invalid);
        }
        fields.push((
            ascii_units("clientId"),
            project_root_field(&oauth, "clientId"),
        ));
    }
    if let Some(value) = root.get_property("callbackPort") {
        if !is_positive_integer(value) {
            return Err(NormalizeValueError::Invalid);
        }
        fields.push((
            ascii_units("callbackPort"),
            project_root_field(&oauth, "callbackPort"),
        ));
    }
    if let Some(value) = root.get_property("authServerMetadataUrl") {
        let Some(units) = value.code_units() else {
            return Err(NormalizeValueError::Invalid);
        };
        let Some(row) = semantics.url(units) else {
            return Err(NormalizeValueError::Unresolved);
        };
        let NativePolicyZodUrlOutcome::Valid {
            protocol_units,
            zod_value_units,
            ..
        } = &row.zod_url
        else {
            return Err(NormalizeValueError::Invalid);
        };
        if protocol_units != &ascii_units("https:")
            || !zod_value_units.starts_with(&ascii_units("https://"))
        {
            return Err(NormalizeValueError::Invalid);
        }
        fields.push((
            ascii_units("authServerMetadataUrl"),
            string_projection_units(zod_value_units),
        ));
    }
    if let Some(value) = root.get_property("scopes") {
        if value.code_units().is_none_or(|units| units.is_empty()) {
            return Err(NormalizeValueError::Invalid);
        }
        fields.push((ascii_units("scopes"), project_root_field(&oauth, "scopes")));
    }
    if let Some(value) = root.get_property("xaa") {
        if value.as_bool().is_none() {
            return Err(NormalizeValueError::Invalid);
        }
        fields.push((ascii_units("xaa"), project_root_field(&oauth, "xaa")));
    }
    Utf16JsonProjection::object_units(fields).map_err(|_| NormalizeValueError::Unresolved)
}

fn normalize_tools(
    server: &Utf16JsonProjection,
    value: JsonValueView<'_>,
) -> Result<Utf16JsonProjection, ()> {
    let length = value.array_len().ok_or(())?;
    let tools = server
        .subprojection_property_units(&ascii_units("tools"))
        .map_err(|_| ())?;
    let mut normalized_tools = Vec::with_capacity(length);
    for index in 0..length {
        let tool = value.get_index(index).ok_or(())?;
        let _name = tool
            .get_property("name")
            .and_then(JsonValueView::code_units)
            .ok_or(())?;
        let tool_projection = tools.subprojection(&format!("/{index}")).map_err(|_| ())?;
        let mut normalized_fields = vec![(
            ascii_units("name"),
            tool_projection
                .subprojection_property_units(&ascii_units("name"))
                .map_err(|_| ())?,
        )];
        if let Some(policy) = tool.get_property("permission_policy") {
            let policy_units = policy.code_units().ok_or(())?;
            if !TOOL_PERMISSION_POLICIES_IN_SCHEMA_ORDER
                .iter()
                .any(|expected| ascii_eq(policy_units, expected))
            {
                return Err(());
            }
            normalized_fields.push((
                ascii_units("permission_policy"),
                tool_projection
                    .subprojection_property_units(&ascii_units("permission_policy"))
                    .map_err(|_| ())?,
            ));
        }
        normalized_tools
            .push(Utf16JsonProjection::object_units(normalized_fields).map_err(|_| ())?);
    }
    Utf16JsonProjection::array(normalized_tools).map_err(|_| ())
}

fn normalize_tool_permissions(
    server: &Utf16JsonProjection,
    value: JsonValueView<'_>,
) -> Result<Utf16JsonProjection, ()> {
    let entries = js_ordered_entries(value).ok_or(())?;
    let permissions = server
        .subprojection_property_units(&ascii_units("toolPermissions"))
        .map_err(|_| ())?;
    let mut fields = Vec::with_capacity(entries.len());
    for entry in entries {
        let policy = entry.value.code_units().ok_or(())?;
        if !TOOL_PERMISSION_POLICIES
            .iter()
            .any(|expected| ascii_eq(policy, expected))
        {
            return Err(());
        }
        // The fixed Zod record parser constructs a normal `{}` result and
        // assigns each parsed value by key. For the special `__proto__`
        // setter, string enum values change no prototype and create no own
        // property; Bun's source oracle confirms the key is absent in output.
        if !ascii_eq(entry.code_units, "__proto__") {
            fields.push((
                entry.code_units.to_vec(),
                permissions
                    .subprojection_property_units(entry.code_units)
                    .map_err(|_| ())?,
            ));
        }
    }
    Utf16JsonProjection::object_units(fields).map_err(|_| ())
}

fn normalize_string_record(server: &Utf16JsonProjection, field: &str) -> Utf16JsonProjection {
    let Some(value) = server.get_property(field) else {
        return Utf16JsonProjection::object(Vec::new()).expect("empty object is valid JSON");
    };
    let Some(entries) = js_ordered_entries(value) else {
        return Utf16JsonProjection::object(Vec::new()).expect("empty object is valid JSON");
    };
    let fields = entries
        .iter()
        .filter(|entry| !ascii_eq(entry.code_units, "__proto__"))
        .filter_map(|entry| {
            Some((
                entry.code_units.to_vec(),
                server
                    .subprojection_property_units(&ascii_units(field))
                    .ok()?
                    .subprojection_property_units(entry.code_units)
                    .ok()?,
            ))
        })
        .collect();
    Utf16JsonProjection::object_units(fields).expect("validated string record has unique keys")
}

fn project_root_field(server: &Utf16JsonProjection, field: &str) -> Utf16JsonProjection {
    server
        .subprojection_property_units(&ascii_units(field))
        .expect("field was validated present")
}

fn js_ordered_entries<'a>(value: JsonValueView<'a>) -> Option<Vec<JsonObjectEntryView<'a>>> {
    let mut entries = value.object_entries()?;
    entries.sort_by(|left, right| {
        match (array_index(left.code_units), array_index(right.code_units)) {
            (Some(left), Some(right)) => left.cmp(&right),
            (Some(_), None) => std::cmp::Ordering::Less,
            (None, Some(_)) => std::cmp::Ordering::Greater,
            (None, None) => std::cmp::Ordering::Equal,
        }
    });
    Some(entries)
}

fn array_index(units: &[u16]) -> Option<u32> {
    if units.is_empty() || (units.len() > 1 && units[0] == 48) {
        return None;
    }
    if units.iter().any(|unit| !matches!(*unit, 48..=57)) {
        return None;
    }
    let text = String::from_utf16(units).ok()?;
    let index = text.parse::<u32>().ok()?;
    (index <= u32::MAX - 1).then_some(index)
}

fn join_path(parent: &[u16], component: &[u16]) -> Vec<u16> {
    if parent.is_empty() {
        component.to_vec()
    } else {
        let mut joined = Vec::with_capacity(parent.len() + 1 + component.len());
        joined.extend_from_slice(parent);
        joined.push(u16::from(b'.'));
        joined.extend_from_slice(component);
        joined
    }
}

fn path_message(path: &[u16], message: &str) -> Utf16JsonProjection {
    let mut message_units = Vec::with_capacity(path.len() + message.len() + 2);
    if path.is_empty() {
        message_units.extend_from_slice(&ascii_units(message));
    } else {
        message_units.extend_from_slice(path);
        message_units.extend(ascii_units(": "));
        message_units.extend(ascii_units(message));
    }
    string_projection_units(&message_units)
}

fn ascii_eq(units: &[u16], expected: &str) -> bool {
    units.iter().copied().eq(expected.encode_utf16())
}

fn ascii_units(value: &str) -> Vec<u16> {
    value.encode_utf16().collect()
}

fn string_projection(value: &str) -> Utf16JsonProjection {
    string_projection_units(&ascii_units(value))
}

fn string_projection_units(units: &[u16]) -> Utf16JsonProjection {
    Utf16JsonProjection::root_string(String::from_utf16_lossy(units), units.to_vec())
        .expect("root string projection uses a display derived from the exact UTF-16 units")
}

fn number_projection(value: f64) -> Utf16JsonProjection {
    Utf16JsonProjection::parse(&value.to_string()).expect("finite number is valid JSON")
}

fn unresolved_result(value: &Utf16JsonProjection) -> NativeManagedMcpServersResult {
    NativeManagedMcpServersResult {
        normalized: Some(value.clone()),
        diagnostics: Vec::new(),
        unresolved: true,
    }
}

