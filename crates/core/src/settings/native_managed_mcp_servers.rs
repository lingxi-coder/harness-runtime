//! Acceptance-only source-derived port of Native `qt` for `managedMcpServers`.
//!
//! This file is a draft beside the static-settings validator. It is not
//! registered in a production crate and was not compiled with Cargo.
//!
//! Fixed-source closure (Claude Code 2.1.295):
//! - Native binary SHA-256: `0116ee2e0a513900b633d9951367f18747686478e2b462805b8c31609f047f70`.
//! - Main raw chunk `src_187673145.js`, binary offset 187673145, 434959 bytes,
//!   SHA-256 `6fbf3e921382e88e71bd834f2034ee24a15cada553c00e95181e44fa033d22aa`.
//! - `At` at binary byte 188060543 invokes `__` after `m_`; `fTr` at
//!   188044910 passes `mcpServerEntrySalvageOnly: true`.
//! - `__` at 188052725 calls `qt` at 187737490. `qt` removes a non-object root,
//!   reports a root warning, and otherwise emits an `Object.create(null)` map
//!   containing only entries accepted by `to().safeParse`.
//! - `to` and the local validators `eo`, `bu`, `lr` are in the main chunk at
//!   187736239, 187735755, 187735856, and 187735954. Its HTTP/SSE schema union
//!   is `Sdt()`/`r0t()`; `MAr` folds `request_timeout_ms` into `timeout` and
//!   clamps that fallback to 300000.
//! - The input schema uses the imported Zod chunk `src_186578912.js` at binary
//!   offset 186578912, 90493 bytes, SHA-256
//!   `8886b2923ae669a979e16ab15d7a8151571d85efcd7471e0ba226d4e2d53559f`.
//!   The field locale comes from `src_186567271.js` (11640 bytes, SHA-256
//!   `5a4c66ea5dd1a86915555f0595322039f87aec3b7f58797233acbdb1515ae4b3`).
//! - Environment-reference matching imports `Bue` from `src_187600574.js` at
//!   binary offset 187600574, 278 bytes, SHA-256
//!   `fcace4391e2d31e612c0ddbc39d3ac46faf4b9b10aa4abacd808a0f8dc64771c`.
//!   Its regex is `\\$\\{([A-Za-z_][A-Za-z0-9_]*)(?::-[^}]*)?\\}`.
//! - The actual Due field is `managedMcpServers:()=>Ae(()=>pe(o().refine(eo),
//!   to(),{error:no}))` at main-chunk binary byte 187899736; At's `qt` and
//!   Due's per-entry validator share the same `to()` schema.
//!
//! The port covers the complete imported HTTP/SSE entry shape, including
//! OAuth, tool declarations, tool permission records, source custom checks,
//! and source-order warning construction. Unicode control/format classification
//! uses the fixed Bun 1.4.3 Unicode 16 table recorded beside this draft.

