#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn common_extensions_resolve_via_aliases() {
        // lur alias → aur display name.
        assert_eq!(language_for_path("/tmp/main.rs"), "Rust");
        assert_eq!(language_for_path("a/b/app.ts"), "TypeScript");
        assert_eq!(language_for_path("x.py"), "Python");
        assert_eq!(language_for_path("mod.tsx"), "TypeScript");
        assert_eq!(language_for_path("h.cpp"), "C++");
    }

    #[test]
    fn canonical_ids_resolve_directly() {
        assert_eq!(language_for_path("q.rust"), "Rust");
        assert_eq!(language_for_path("conf.toml"), "TOML, also INI");
        assert_eq!(language_for_path("s.cedar"), "Cedar");
    }

    #[test]
    fn case_is_folded_like_to_lower_case() {
        assert_eq!(language_for_path("MAIN.RS"), "Rust");
    }

    #[test]
    fn unknown_missing_and_dotfile_extensions() {
        assert_eq!(language_for_path("Makefile.custom-ext"), "unknown");
        assert_eq!(language_for_path("noext"), "unknown");
        assert_eq!(language_for_path("/etc/.bashrc"), "unknown");
        assert_eq!(language_for_path("trailing."), "unknown");
        // .ipynb is absent from the highlight.js registry in the binary too.
        assert_eq!(language_for_path("nb.ipynb"), "unknown");
    }
}
