//! Extension → language display-name mapping for the
//! `claude_code.code_edit_tool.decision` counter's `language` attribute.
//!
//! 1:1 port of the binary's `UMt(path)` resolver (2.1.220): `path.extname`
//! minus the dot, lowercased, resolved through the highlight.js registry —
//! canonical ids (`aur`), aliases (`lur`, e.g. `rs → rust`, `ts →
//! typescript`), then the static extras (`ACs`: `cedar`/`cedarpolicy`) —
//! falling back to `"unknown"`. The dynamic plugin-language branch (`Btd`,
//! fed by highlight plugins registered at runtime) has no LingXi equivalent
//! and is an empty set at CC boot, so it is omitted.
//!
//! The table below is GENERATED from the 2.1.220 binary (`aur` ∪ resolved
//! `lur` ∪ `ACs`, 385 arms) — regenerate with the extraction script rather
//! than hand-editing entries.

/// Resolve the `language` attribute for a code-edit tool decision from the
/// tool's target file path (binary `UMt`). Returns `"unknown"` for missing,
/// empty, or unmapped extensions — the attribute is still attached in that
/// case, exactly like CC (only a missing PATH omits it; see the caller).
#[must_use]
pub(crate) fn language_for_path(path: &str) -> &'static str {
    let Some(ext) = file_extension(path) else {
        return "unknown";
    };
    if ext.is_empty() {
        return "unknown";
    }
    language_for_extension(&ext.to_lowercase())
}

/// Node `path.extname(path).slice(1)`: the substring after the last `.` of the
/// basename. `None` when there is no `.`, or the `.` is the basename's first
/// character (dotfiles like `.bashrc` have no extension); `Some("")` for a
/// trailing dot (`foo.`), which the caller maps to `"unknown"`.
fn file_extension(path: &str) -> Option<&str> {
    let base = path.rsplit('/').next().unwrap_or(path);
    let dot = base.rfind('.')?;
    if dot == 0 {
        return None;
    }
    Some(&base[dot + 1..])
}

