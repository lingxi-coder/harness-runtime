export function register(on) {
  on('plugin.register', (_, e, next) => next(e));
  on('prompt.context', (_, e, next) => next(e));
  on('prompt.submit', (_, e, next) => next(e));
  on('prompt.section', { name: 'memory' }, (_, e, next) => next(e));
  on('prompt.compose', (_, e, next) => next(e));
  on('session.start', async ($, e, next) => {
    await $.command.run({ command: 'fixture' });
    return next(e);
  });
  on('session.end', (_, e, next) => next(e));
  on('settings.read', (_, e, next) => next(e));
  on('env.get', (_, e, next) => next(e));
  on('env.set', (_, e, next) => next(e));
  on('telemetry.log', { to: 'collector' }, (_, e, next) => next(e));
  on('telemetry.mark', { to: 'collector' }, (_, e, next) => next(e));
  on('ui.log', (_, e, next) => next(e));
  on('ui.toast', (_, e, next) => next(e));
  on('ui.status', (_, e, next) => next(e));
  on('tool.check', (_, e, next) => next(e));
  on('tool.list', (_, e, next) => next(e));
  on('command.list', (_, e, next) => next(e));
  on('command.register', (_, e, next) => next(e));
  on('command.run', (_, e, next) => next(e));
  on('tool.register', (_, e, next) => next(e));
  on('clock.now', (_, e, next) => next(e));
  on('clock.sleep', (_, e, next) => next(e));
  on('clock.after', (_, e, next) => next(e));
  on('clock.every', (_, e, next) => next(e));
  on('process.run', (_, e, next) => next(e));
  on('session.cwd', (_, e, next) => next(e));
  on('session.root', (_, e, next) => next(e));
  on('session.model', (_, e, next) => next(e));
  on('session.id', (_, e, next) => next(e));
  on('session.turns', (_, e, next) => next(e));
  on('session.repo', (_, e, next) => next(e));
  on('session.version', (_, e, next) => next(e));
  on('session.messages', (_, e, next) => next(e));
  on('session.surfaces', (_, e, next) => next(e));
  on('session.surface', (_, e, next) => next(e));
  on('model.fork', (_, e, next) => next(e));
  on('model.complete', (_, e, next) => next(e));
  on('model.classify', (_, e, next) => next(e));
  on('state.get', (_, e, next) => next(e));
  on('state.set', (_, e, next) => next(e));
  on('fs.read', (_, e, next) => next(e));
  on('fs.write', (_, e, next) => next(e));
  on('fs.exists', (_, e, next) => next(e));
  on('fs.list', (_, e, next) => next(e));
  on('fs.stat', (_, e, next) => next(e));
  on('fs.ancestors', (_, e, next) => next(e));
  on('store.get', (_, e, next) => next(e));
  on('store.set', (_, e, next) => next(e));
  on('store.delete', (_, e, next) => next(e));
  on('store.keys', (_, e, next) => next(e));
  on('fs.*', (_, e, next) => next(e));
  on('!tool.call', (_, e, next) => next(e));
  on('tool.call', async ($, e, next) => {
    $.ui.log('fixture log', { to: 'debug' });
    $.ui.toast('fixture toast', { timeoutMs: 4000 });
    $.ui.status('fixture status');
    $.ui.invalidate('prompt.section');
    $.ui.invalidate('prompt.context');
    await $.tool.check({ tool: 'Read', input: { file_path: 'README.md' } });
    await $.tool.list();
    await $.command.list();
    await $.command.register({ name: 'fixture', description: 'Fixture command' });
    await $.tool.register({ name: 'fixture', description: 'Fixture tool' });
    await $.clock.now();
    await $.clock.sleep(0);
    $.clock.after(0, () => {}).cancel();
    $.clock.every(1, () => {}).cancel();
    await $.process.run(['git', 'status']);
    await $.session.cwd();
    await $.session.root();
    await $.session.model();
    await $.session.id();
    await $.session.turns();
    await $.session.repo();
    await $.session.version();
    await $.session.messages();
    await $.session.messages({ as: 'api' });
    await $.session.surfaces();
    await $.session.surface();
    await $.model.fork({ prompt: 'fixture question' });
    await $.model.complete({ model: 'haiku', prompt: 'fixture question' });
    await $.model.classify('fixture text', ['yes', 'no']);
    if (false) await $.prompt.submit({ text: 'fixture follow up', asUser: true });
    await $.state.get({ plugin: 'mod-api-validate', key: 'counter' });
    await $.state.set({ plugin: 'mod-api-validate', key: 'counter' }, 1);
    await $.prompt.compose();
    await $.prompt.context({ blocks: [] });
    await $.settings.read({ source: 'policy' });
    await $.env.get('HOME');
    await $.env.set('GIT_PAGER', 'cat');
    await $.telemetry.log({ event: 'fixture' });
    await $.telemetry.mark({ feature: 'fixture', kind: 'fixture' });
    await $.fs.read('README.md');
    await $.fs.write('example.txt', 'hello');
    await $.fs.exists('example.txt');
    await $.fs.list();
    await $.fs.stat('example.txt', { resolve: true });
    await $.fs.ancestors({ names: ['AGENTS.md'] });
    await $.store.get('fixture');
    await $.store.set('fixture', { checked: true });
    await $.store.keys();
    await $.store.delete('fixture');
    return next(e);
  });
}
